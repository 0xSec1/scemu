# Offsets are according to X86 Windows10 22H2 kernel
#LIST_ENTRY offsets
FLINK = 0x0
BLINK = 0x4

#_UNICODE_STRING offsets
LENGTH = 0x0
MAXIMUM_LENGTH = 0x2
BUFFER = 0x4

#_PEB member offsets
LDR = 0xC    #structure of _PEB_LDR_DATA

#LIST_ENTRY offsets inside LDR_TABLE_DATA_ENTRY
IN_LOAD_ORDER_LINKS = 0x0
IN_MEMORY_ORDER_LINKS = 0x8
IN_INITIALIZATION_ORDER_LINKS = 0x10

#_PEB_LDR_DATA member offsets
LDR_IN_LOAD_ORDER_MODULE_LIST = 0xC     #structure of _LIST_ENTRY{Flink, Blink}
LDR_IN_MEMORY_ORDER_MODULE_LIST = 0x14
LDR_IN_INITIALIZATION_ORDER_MODULE_LIST = 0x1C

#_LDR_TABLE_DATA_ENTRY offsets
DLL_BASE = 0x18
ENTRY_POINT = 0x1C
SIZE_OF_IMAGE = 0x20
FULL_DLL_NAME = 0x24  #struct _UNICODE_STRING FullDllName;
BASE_DLL_NAME = 0x2C  #struct _UNICODE_STRING BaseDllName;
